# Sample Data
marks <- c(85, 78, 90, 88, 76, 95, 82, 79)

# Mean
cat("Mean:", mean(marks), "\n")

# Median
cat("Median:", median(marks), "\n")

# Variance
cat("Variance:", var(marks), "\n")

# Standard Deviation
cat("Standard Deviation:", sd(marks), "\n")

# Range
cat("Range:", range(marks), "\n")

# Summary Statistics
summary(marks)